COL = {  # glyph char -> (css fill, literal for exported svg)
    'L': ('var(--ic-l,#c8c7ff)', '#c8c7ff'), 'T': ('var(--ic-t,#7fffd4)', '#7fffd4'),
    'W': ('#ffffff', '#ffffff'), 'D': ('#241a3a', '#241a3a'),
    'F': ('var(--ic-face,#57068c)', '#57068c'), 'H': ('var(--ic-hi,#c8c7ff)', '#c8c7ff'), 'S': ('#241a3a', '#241a3a'),
}

def drawn(fn):
    return [''.join(fn(x, y) for x in range(12)) for y in range(12)]

def x_logo(x, y):   # X: thick stroke top-left to bottom-right, thin stroke the other way
    if abs(x - y) <= 1 and 0 < y < 11 or (x, y) in ((0, 0), (1, 0), (11, 11), (10, 11)): return 'L'
    if x + y == 11 and y not in (5, 6): return 'T'
    return '.'

def rss(x, y):
    d = math.hypot(x + .5, 11.5 - y)
    if d < 2.6: return 'T'
    if 5 <= d < 6.6 or 9 <= d < 10.6: return 'L'
    return '.'

