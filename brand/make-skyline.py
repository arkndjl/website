"""Pixel New York skyline for the about/contact page (layouts/shortcodes/aboutcontact.html).
288 x 48 pixel grid (3 px per pixel on desktop; phones show the middle), drawn as <rect>s; classes: s = sky band, b = building, e = edge highlight,
w = lit window (teal), v = lit window (lilac), k = blinking window, t = star. Colours live in the shortcode CSS.
Run: python3 brand/make-skyline.py  (writes layouts/partials/px/skyline.html)"""
import pathlib, random
ROOT = pathlib.Path(__file__).resolve().parent.parent
W, H = 288, 48
rnd = random.Random(212)
grid = [[None] * W for _ in range(H)]

def fill(x0, y0, x1, y1, c):
    for y in range(max(0, y0), min(H, y1)):
        for x in range(max(0, x0), min(W, x1)):
            grid[y][x] = c

def tower(x, w, h, win=True):
    top = H - h
    fill(x, top, x + w, H, 'b')
    fill(x, top, x + 1, H, 'e')          # lit left edge
    if win:
        for y in range(top + 2, H - 2, 3):
            for xx in range(x + 2, min(W, x + w - 1), 2):
                r = rnd.random()
                if r < .07: grid[y][xx] = 'k'
                elif r < .22: grid[y][xx] = 'w'
                elif r < .32: grid[y][xx] = 'v'

# background row of low buildings
x = 0
while x < W:
    w = rnd.choice([5, 6, 7, 8, 9])
    tower(x, w, rnd.randint(9, 20))
    x += w + rnd.choice([0, 1])

# Empire State Building: setbacks + mast
def empire(x):
    tower(x, 15, 26)
    tower(x + 2, 11, 30)
    tower(x + 4, 7, 35, win=False)
    fill(x + 5, H - 38, x + 10, H - 35, 'b')
    fill(x + 6, H - 41, x + 9, H - 38, 'b')
    fill(x + 7, H - 46, x + 8, H - 41, 'e')

# Chrysler Building: stepped arches + spire
def chrysler(x):
    tower(x, 11, 27)
    for i, (a, b) in enumerate([(1, 10), (2, 9), (3, 8), (4, 7)]):
        y = H - 29 - 2 * i
        fill(x + a, y, x + b, y + 2, 'b')
        if (i % 2) == 0:
            for xx in range(x + a + 1, x + b - 1, 2): grid[y][xx] = 'v'
    fill(x + 5, H - 44, x + 6, H - 35, 'e')

# One World Trade Center: tapered + spire
def owtc(x):
    for i in range(36):
        y = H - 1 - i
        inset = i // 9
        fill(x + inset, y, x + 13 - inset, y + 1, 'b')
        grid[y][x + inset] = 'e'
    for y in range(H - 34, H - 2, 3):
        for xx in range(x + 3, x + 10, 2):
            if rnd.random() < .25: grid[y][xx] = 'w'
    fill(x + 6, H - 47, x + 7, H - 36, 'e')

owtc(92)
empire(136)
chrysler(178)
tower(40, 9, 22); tower(62, 8, 25); tower(116, 9, 24); tower(162, 8, 21); tower(200, 10, 26); tower(226, 8, 23); tower(250, 9, 20)

# sky: four bands, stars
bands = [(0, 10, 's1'), (10, 20, 's2'), (20, 30, 's3'), (30, H, 's4')]
stars = []
for _ in range(48):
    sx, sy = rnd.randrange(W), rnd.randrange(0, 22)
    if grid[sy][sx] is None: stars.append((sx, sy))

def runs():
    out = []
    for y in range(H):
        x = 0
        while x < W:
            c = grid[y][x]
            if c is None: x += 1; continue
            x0 = x
            while x < W and grid[y][x] == c: x += 1
            out.append(f'<rect class="{c}" x="{x0}" y="{y}" width="{x - x0}" height="1"/>')
    return out

parts = [f'<rect class="{c}" x="0" y="{a}" width="{W}" height="{b - a}"/>' for a, b, c in bands]
parts += [f'<rect class="t" x="{sx}" y="{sy}" width="1" height="1"/>' for sx, sy in stars]
parts += runs()
svg = (f'<svg class="ac-sky" viewBox="0 0 {W} {H}" preserveAspectRatio="xMidYMax slice" shape-rendering="crispEdges" '
       f'aria-hidden="true" focusable="false">' + ''.join(parts) + '</svg>\n')
(ROOT / 'layouts/partials/px/skyline.html').write_text(
    '{{- /* Generated by brand/make-skyline.py: pixel New York skyline. */ -}}\n' + svg)
print('skyline:', len(parts), 'rects')
