def sheet(sprites):
    kfs = sorted({len(f) for f in sprites.values()})
    css = SHEET_CSS + ''.join(
        f'@keyframes px-step-{n} {{ 0% {{ visibility: visible; }} {100 / n:.4f}% {{ visibility: hidden; }} 100% {{ visibility: hidden; }} }}\n'
        for n in kfs)
    parts = ['<!doctype html>\n<html lang="en"><head><meta charset="utf-8"><title>Pixel art sheet</title>',
             f'<style>{css}</style></head><body>',
             '<h1>arkndjl pixel art</h1>',
             f'<p class="meta">brand/make-pixel-art.py &middot; {len(sprites)} sprites &middot; every frame at {SCALE}&times; '
             '&middot; layouts/partials/px/&lt;name&gt;.html</p><div class="pal">']
    for c, hexv in PALETTE.items():
        parts.append(f'<span><i style="background:{hexv}"></i>{c} {hexv}</span>')
    parts.append('<span><i style="background:transparent"></i>. transparent</span></div>')
    for name, frames in sprites.items():
        h, w = len(frames[0]), len(frames[0][0])
        n = len(frames)
        parts.append(f'<section class="win"><div class="bar"><span>px/{name}.html</span>'
                     f'<span><b>{w}&times;{h}</b> &middot; {n} frames</span></div><div class="frames">')
        for i, rows in enumerate(frames):
            parts.append(f'<figure><svg viewBox="0 0 {w} {h}" width="{w * SCALE}" height="{h * SCALE}" shape-rendering="crispEdges">'
                         f'{rects_class(rows)}</svg><figcaption>f{i}</figcaption></figure>')
        loop = partial(name, frames).replace('\n', '')
        loop = loop.replace(f'width="{w}" height="{h}"', f'width="{w * SCALE}" height="{h * SCALE}"', 1)
        loop = loop.replace('<svg ', f'<svg style="--n:{n};--dur:{n * 0.16:.2f}s;--kf:px-step-{n}" ', 1)
        parts.append(f'<figure class="loop">{loop}<figcaption>loop</figcaption></figure></div></section>')
    parts.append('</body></html>\n')
    return '\n'.join(parts)


