    sprites = {name: parse(name, frames) for name, frames in SPRITES.items()}
    assert set(sprites) == set(EXPECT), set(EXPECT) ^ set(sprites)
    pdir = ROOT / 'layouts/partials/px'
    xdir = ROOT / 'brand/exports/pixelart'
    pdir.mkdir(parents=True, exist_ok=True)
    xdir.mkdir(parents=True, exist_ok=True)
    for old in xdir.glob('*-f*.svg'):
        old.unlink()
    for name, frames in sprites.items():
        (pdir / f'{name}.html').write_text(partial(name, frames))
        for i, rows in enumerate(frames):
            (xdir / f'{name}-f{i}.svg').write_text(preview(rows))
    (xdir / 'sheet.html').write_text(sheet(sprites))
    print('pixel art:', ', '.join(f'{k} {len(v[0][0])}x{len(v[0])}x{len(v)}' for k, v in sprites.items()))
    # contact sheet PNG (Playwright); skipped with a hint if node/playwright are unavailable
    js = ROOT / 'brand/render-pixelart.js'
    if shutil.which('node'):
        r = subprocess.run(['node', str(js)], cwd=ROOT)
        if r.returncode == 0:
            return
    print('sheet.png not rendered: run  NODE_PATH=<dir with playwright> node brand/render-pixelart.js')


