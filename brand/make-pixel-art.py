def parse(name, frames):
    """ASCII frames -> list of row lists; checks size, frame count and palette."""
    w, h, n = EXPECT[name]
    out = []
    for i, art in enumerate(frames):
        rows = art.strip('\n').split('\n')
        assert len(rows) == h and all(len(r) == w for r in rows), f'{name} f{i}: expected {w}x{h}'
        bad = set(''.join(rows)) - set(PALETTE) - {'.'}
        assert not bad, f'{name} f{i}: unknown codes {bad}'
        out.append(rows)
    assert len(out) == n, f'{name}: expected {n} frames, got {len(out)}'
    return out


def runs(rows):
    """Horizontal same-colour runs: (code, x, y, width)."""
    for y, row in enumerate(rows):
        x = 0
        while x < len(row):
            c = row[x]
            x0 = x
            while x < len(row) and row[x] == c:
                x += 1
            if c != '.':
                yield c, x0, y, x - x0


def rects(rows):
    """Row runs, with identical runs on consecutive rows stacked into one taller rect.
    Every pixel is covered exactly once (no overdraw): (code, x, y, width, height)."""
    out, open_ = [], {}
    for y in range(len(rows) + 1):
        here = {(c, x, w) for c, x, yy, w in runs([rows[y]])} if y < len(rows) else set()
        for key in [k for k in open_ if k not in here]:
            c, x, w = key
            y0 = open_.pop(key)
            out.append((c, x, y0, w, y - y0))
        for key in here:
            open_.setdefault(key, y)
    return sorted(out, key=lambda r: (r[2], r[1]))


def rects_class(rows):
    return ''.join(f'<rect class="{c}" x="{x}" y="{y}" width="{w}" height="{h}"/>' for c, x, y, w, h in rects(rows))


def rects_fill(rows):
    return ''.join(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" fill="{PALETTE[c]}"/>' for c, x, y, w, h in rects(rows))


def partial(name, frames):
    h, w = len(frames[0]), len(frames[0][0])
    lines = [f'<svg class="px px--{name} px--n{len(frames)}" viewBox="0 0 {w} {h}" width="{w}" height="{h}" '
             f'shape-rendering="crispEdges" aria-hidden="true" focusable="false">']
    for i, rows in enumerate(frames):
        lines.append(f'<g class="px__f" style="--i:{i}">{rects_class(rows)}</g>')
    lines.append('</svg>')
    return '\n'.join(lines) + '\n'


def preview(rows):
    h, w = len(rows), len(rows[0])
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}" width="{w}" height="{h}" shape-rendering="crispEdges">'
            f'<rect width="{w}" height="{h}" fill="{PALETTE["p"]}"/>{rects_fill(rows)}</svg>\n')


